export function pick<T>(a: T[]): T {
  return a[Math.floor(Math.random() * a.length)];
}

/** Fill placeholders; fix 이(가)/을(를)/(이)랑 after names. */
export function fill(s: string, vars: Record<string, string>): string {
  let out = s.replace(/\{(\w+)\}/g, (_, k: string) => vars[k] ?? "");
  const fin = (w: string) => {
    const c = w.charCodeAt(w.length - 1);
    return c >= 0xac00 && c <= 0xd7a3 && (c - 0xac00) % 28 !== 0;
  };
  out = out.replace(/([가-힣A-Za-z0-9]+)이\(가\)/g, (_, w: string) => w + (fin(w) ? "이" : "가"));
  out = out.replace(/([가-힣A-Za-z0-9]+)을\(를\)/g, (_, w: string) => w + (fin(w) ? "을" : "를"));
  out = out.replace(/ +([.!?])/g, "$1").replace(/ {2,}/g, " ");
  return out;
}
